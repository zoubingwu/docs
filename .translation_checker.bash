#!/bin/bash

# TiDB Cloud 文档翻译进度检查器
# 每30秒启动一次 q chat，让AI检查翻译进度并自动打勾

LOG_FILE="agent_monitor.log"

log_message() {
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] $1" | tee -a "$LOG_FILE"
}

# 主循环
while true; do
    log_message "开始新一轮翻译进度检查..."

    # 启动 q chat 并传入检查指令
    q chat --trust-all-tools << 'EOF'
你是一个专业的翻译进度检查助手。请按照以下步骤执行：

## 任务目标
检查 TiDB Cloud 中文文档的翻译进度，确保翻译质量并更新进度记录。

## 执行步骤

### 1. 列出待检查文件
首先列出 `tidb-cloud-cn` 目录下的所有 .md 文件。

### 2. 检查进度状态
查看 `.translation_progress.md` 文件，找出所有未完成的项目（没有打勾 ✅ 的项目）。

### 3. 质量检查
对于每个未完成的文件，请：
- 比较中文版本（tidb-cloud-cn/文件名）与英文原版（tidb-cloud/文件名）
- 检查内容是否完整对应，没有遗漏的段落或章节
- 验证专业术语翻译是否准确
- 确认格式（标题、列表、代码块等）是否保持一致
- 检查链接是否正确

### 4. 更新进度
如果文件翻译质量合格（内容完整、翻译准确、格式正确），则：
- 在 `.translation_progress.md` 中将对应的 `- [ ]` 改为 `- [x]`
- 只处理确实已经完成翻译且质量合格的文件

### 5. 报告结果
简要报告本轮检查的结果：
- 检查了多少个文件
- 新完成了多少个文件（打勾）
- 发现了什么问题需要注意

## 注意事项
- 严格按照质量标准，不要对质量不合格的文件打勾
- 如果发现翻译问题，请具体说明问题所在
- 优先检查文件大小相近的中英文对照文件
- 保持谨慎和客观的态度

请开始执行检查任务。
EOF

    log_message "本轮检查完成，等待30秒后开始下一轮..."
    sleep 60
done
